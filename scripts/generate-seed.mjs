#!/usr/bin/env node
// Generates Flyway seed migrations for catalog-service and inventory-service from
// infra/seed/catalog.json so SKUs stay consistent across the two owners.
// Usage: node scripts/generate-seed.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(join(root, 'infra/seed/catalog.json'), 'utf8'));
const q = (s) => (s === null || s === undefined ? 'NULL' : `'${String(s).replaceAll("'", "''")}'`);
const header = '-- GENERATED by scripts/generate-seed.mjs from infra/seed/catalog.json. Do not edit by hand.\n-- Development seed data only (original placeholder catalogue).\n';

const skuFor = (p, i) => `${p.slug.split('-')[0].toUpperCase().slice(0, 8)}-${String(i + 1).padStart(2, '0')}`;

let catalog = header;
data.collections.forEach((c, i) => {
  catalog += `INSERT INTO collections (slug, name, description, is_bulk, sort_order) VALUES (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${c.bulk}, ${i});\n`;
});
const seen = new Set();
data.products.forEach((p, idx) => {
  const created = `now() - interval '${(data.products.length - idx) * 3} days'`;
  catalog += `INSERT INTO products (slug, name, description, collection_id, fabric, craft, occasion, price_paise, bulk_price_paise, motif, is_new, featured_rank, max_per_order, created_at, updated_at)\n` +
    `  SELECT ${q(p.slug)}, ${q(p.name)}, ${q(p.description)}, id, ${q(p.fabric)}, ${q(p.craft)}, ${q(p.occasion)}, ${p.price * 100}, ${p.bulkPrice ? p.bulkPrice * 100 : 'NULL'}, ${q(p.motif)}, ${!!p.isNew}, ${idx < 8 ? idx + 1 : 'NULL'}, ${p.bulkPrice ? 10 : 5}, ${created}, ${created} FROM collections WHERE slug = ${q(p.collection)};\n`;
  p.variants.forEach((v, i) => {
    const sku = skuFor(p, i);
    if (seen.has(sku)) throw new Error(`duplicate sku ${sku}`);
    seen.add(sku);
    catalog += `INSERT INTO product_variants (product_id, sku, color_name, color_family, color_hex, accent_hex, position) SELECT id, ${q(sku)}, ${q(v.color)}, ${q(v.family)}, ${q(v.hex)}, ${q(v.accent)}, ${i} FROM products WHERE slug = ${q(p.slug)};\n`;
  });
});

let inventory = header;
data.products.forEach((p) => p.variants.forEach((v, i) => {
  inventory += `INSERT INTO stock_levels (sku, on_hand, reserved) VALUES (${q(skuFor(p, i))}, ${v.stock}, 0);\n`;
  inventory += `INSERT INTO stock_movements (sku, delta_on_hand, delta_reserved, reason, reference) VALUES (${q(skuFor(p, i))}, ${v.stock}, 0, 'SEED', 'seed');\n`;
}));

const out = [
  ['apps/storefront/src/data/catalog.json', JSON.stringify(data, null, 2) + '\n'],
  ['services/catalog-service/src/main/resources/db/migration/V2__seed_catalog.sql', catalog],
  ['services/inventory-service/src/main/resources/db/migration/V2__seed_stock.sql', inventory],
];
for (const [file, sql] of out) {
  mkdirSync(dirname(join(root, file)), { recursive: true });
  writeFileSync(join(root, file), sql);
  console.log('wrote', file);
}
